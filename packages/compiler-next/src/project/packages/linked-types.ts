/**
 * Types for a linked package's public imports (`wiki/compiler/linking.md`, "Publishing and
 * installing one"). A linked package has nothing built and no `exports`, so TypeScript cannot find
 * `kit/tabs` by itself. It does look for `tabs.d.ts` in the package's root, in editors and `tsc`, for
 * every app in the workspace, so one file per public import is written there.
 *
 * The alternatives were tried against a real type check and were worse: a declared module cannot
 * name a file by path at all (TS2439, hidden by `skipLibCheck`), writing `types` into the author's
 * `package.json` breaks the promise that it is only read, and generated `paths` need every app to
 * change its tsconfig. These files hold relative paths only, so they can be committed. A file the
 * author wrote at such a path is left alone, and `.memoized/linked-types.json` in the package
 * records what to remove when a public import goes.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { parse } from 'yuku-parser';
import type { LinkedImport } from './native';

/** Marks a file as ours to replace or remove. Anything else at that path is the author's. */
const HEADER = '// Generated by memoized-dom: the types of this public import.\n';

/** Writes the type files of every linked package's public imports, and removes stale ones. */
export function writeLinkedTypes(imports: readonly LinkedImport[]): void {
  const byPackage = new Map<string, LinkedImport[]>();
  for (const linked of imports) {
    byPackage.set(linked.directory, [...(byPackage.get(linked.directory) ?? []), linked]);
  }

  for (const [directory, packageImports] of byPackage) {
    for (const linked of packageImports) writeTypeFile(linked);

    // Remove what an earlier run wrote for a public import that has since gone.
    const record = join(directory, '.memoized', 'linked-types.json');
    const previous = JSON.parse(readIfExists(record) ?? '[]') as string[];
    const current = packageImports.map((linked) => typeFileOf(linked.path));
    for (const name of previous) {
      const file = join(directory, name);
      if (!current.includes(name) && readIfExists(file)?.startsWith(HEADER) === true) rmSync(file, { force: true });
    }
    if (JSON.stringify(previous) !== JSON.stringify(current)) {
      mkdirSync(dirname(record), { recursive: true });
      writeFileSync(record, JSON.stringify(current));
    }
  }
}

/** `./deep/field` is found at `deep/field.d.ts` in the package, and `.` at `index.d.ts`. */
function typeFileOf(publicPath: string): string {
  return publicPath === '.' ? 'index.d.ts' : `${publicPath.slice(2)}.d.ts`;
}

function writeTypeFile(linked: LinkedImport): void {
  const file = join(linked.directory, typeFileOf(linked.path));
  const fromFile = relative(dirname(file), linked.file).replaceAll('\\', '/').replace(/\.(?:tsx?|jsx?|tsrx)$/, '');
  const target = JSON.stringify(fromFile.startsWith('.') ? fromFile : `./${fromFile}`);
  // `export *` leaves out a default export, which needs its own line.
  const defaultExport = hasDefaultExport(readFileSync(linked.file, 'utf8')) ? `export { default } from ${target};\n` : '';
  const content = `${HEADER}export * from ${target};\n${defaultExport}`;
  const existing = readIfExists(file);

  // An unchanged file keeps its timestamp, and a file the author wrote stays theirs.
  if (existing === content || (existing !== null && !existing.startsWith(HEADER))) return;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}

function hasDefaultExport(source: string): boolean {
  const { program } = parse(source, { lang: 'tsx', sourceType: 'module' });
  type Statement = { type: string; specifiers?: { exported?: { name?: string; value?: string } }[] };
  return (program.body as unknown as Statement[]).some((statement) => {
    return statement.type === 'ExportDefaultDeclaration'
      || (statement.type === 'ExportNamedDeclaration' && (statement.specifiers ?? []).some((specifier) => {
        return specifier.exported?.name === 'default' || specifier.exported?.value === 'default';
      }));
  });
}

function readIfExists(file: string): string | null {
  return existsSync(file) ? readFileSync(file, 'utf8') : null;
}
