/**
 * What the analysis of server functions generates (`wiki/compiler/server.md`): the client facade
 * each module becomes in a client build, and the typed declarations of `#server-functions`.
 * The text matches the old compiler's generators, which the tests compare against.
 */
import { CompileError } from '../core/diagnostics';
import type { ServerFunctionDefinition, ServerFunctionModule } from './functions';

/**
 * The facade of one module: each function calls its endpoint with `$fetch` (or a streaming or
 * page source), passing its parameters in the query for a GET and in a JSON body otherwise.
 */
export function serverFunctionClient(module: ServerFunctionModule, dataModule = '@memoized-dom/data'): string {
  const lines = [`import { $fetch as __mmd_fetch } from ${JSON.stringify(dataModule)};`];
  if (module.functions.some((fn) => fn.live || fn.generator)) {
    lines.push(`import { createStreamingSource as __mmd_stream } from ${JSON.stringify(`${dataModule}/internal`)};`);
  }
  if (module.functions.some((fn) => fn.page)) {
    lines.push(
      `import { createPageSource as __mmd_page } from ${JSON.stringify(`${dataModule}/internal`)};`,
      `import { loadPageBinding as __mmd_pageBinding } from 'virtual:memoized-dom/page-bindings';`,
    );
  }
  for (const fn of module.functions) lines.push(clientFunction(fn));
  return `${lines.join('\n')}\n`;
}

function clientFunction(fn: ServerFunctionDefinition): string {
  const parameters = fn.parameters.map((parameter) => parameter.name).join(', ');
  const none = fn.parameters.length === 0;
  const path = JSON.stringify(fn.path);
  const method = JSON.stringify(fn.method);

  if (fn.page) {
    if (fn.generator) throw new CompileError('page() generator results are not supported', fn.path);
    const options = fn.method === 'GET'
      ? none ? '{}' : fn.schemaInput ? `{query:{input:JSON.stringify(${parameters})}}` : `{query:{${parameters}}}`
      : `{method:${method}${none ? '' : fn.schemaInput ? `,body:JSON.stringify(${parameters}),headers:{'content-type':'application/json'}` : `,body:{${parameters}}`}}`;
    return `export function ${fn.exported}(${parameters}) { return __mmd_page(${path}, ${options}, ${fn.live ? '"live"' : 'undefined'}, __mmd_pageBinding); }`;
  }

  if (fn.live || fn.generator) {
    const options = fn.method === 'GET'
      ? none ? '{}' : fn.schemaInput ? `{ query: { input: JSON.stringify(${parameters}) } }` : `{ query: { ${parameters} } }`
      : `{ method: ${method}, ${none ? '' : fn.schemaInput ? `body: JSON.stringify(${parameters}), headers: { 'content-type': 'application/json' }` : `body: { ${parameters} }`} }`;
    return `export function ${fn.exported}(${parameters}) { return __mmd_stream(${path}, ${options}, ${JSON.stringify(fn.live ? 'live' : 'generator')}); }`;
  }

  if (fn.method === 'GET') {
    const options = none ? '' : fn.schemaInput ? `, { query: { input: JSON.stringify(${parameters}) } }` : `, { query: { ${parameters} } }`;
    return `export function ${fn.exported}(${parameters}) { return __mmd_fetch(${path}${options}); }`;
  }
  const body = none ? '' : fn.schemaInput
    ? `, body: JSON.stringify(${parameters}), headers: { 'content-type': 'application/json' }`
    : `, body: { ${parameters} }`;
  return `export function ${fn.exported}(${parameters}) { return __mmd_fetch(${path}, { method: ${method}${body} }); }`;
}

/**
 * The declarations of the flat `#server-functions` barrel. Each signature refers to the real
 * implementation through a type-only import, so it never pulls server code into a client build:
 * a GET returns the `$fetch` value, a mutation a promise. Names must be unique across modules.
 */
export function serverFunctionDeclarations(
  modules: readonly ServerFunctionModule[],
  resolveImplementation: (moduleId: string) => string,
  dataModule = '@memoized-dom/data',
): string {
  const lines = [
    '// Generated by @memoized-dom/compiler — client facade declarations for the application server functions.',
    `import type { ResolvedValue } from ${JSON.stringify(dataModule)};`,
    `import type { ErrorResponse, JsonResponse, ServerFunctionArguments, ServerFunctionResult } from '@memoized-dom/server';`,
    'type __mmdClientValue<T> = T extends ErrorResponse ? never : T extends JsonResponse<infer U> ? U : T extends Response ? unknown : T;',
  ];
  const owners = new Map<string, string>();
  const statements: string[] = [];
  let aliases = 0;

  for (const module of modules) {
    if (module.functions.length === 0) continue;
    const alias = `__mmd_impl_${aliases++}`;
    lines.push(`import type * as ${alias} from ${JSON.stringify(resolveImplementation(module.moduleId))};`);
    for (const fn of module.functions) {
      const owner = owners.get(fn.exported);
      if (owner !== undefined) {
        throw new CompileError(`[MMD-S012] server function name '${fn.exported}' is exported by both '${owner}' and '${module.moduleId}'; the '#server-functions' barrel requires unique exported names`, module.moduleId);
      }
      owners.set(fn.exported, module.moduleId);
      const target = `${alias}.${fn.exported}`;
      const result = `__mmdClientValue<Awaited<ServerFunctionResult<typeof ${target}>>>`;
      const returned = fn.method === 'GET' ? `ResolvedValue<${result}>` : `Promise<${result}>`;
      statements.push(`export declare function ${fn.exported}(...args: ServerFunctionArguments<typeof ${target}>): ${returned};`);
    }
  }
  return `${[...lines, ...statements].join('\n')}\n`;
}
