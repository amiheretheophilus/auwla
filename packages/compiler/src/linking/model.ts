import type * as t from '../ast/compiler-types';
import type { AstComment, BaseNode, EstreeFrontend } from '../ast';
import type { ComponentGraphNode } from '../component-linker';
import type { PlainListReturn } from '../analysis/plain-list-return';
import type { ComponentExportInfo } from '../components/manifest';
import type { CompilerRoutedPreparation } from '../routed';
import type { InitialRenderPlan } from '../planning/initial-content';
import type { InitialDelivery } from '../dom/delivery-plan';
import type { ComponentPropUsage } from '../components/render-usage';
import type {
  ParameterWrite,
  ParameterSourceRead,
  MemoDomOptions,
  StateKind,
  TransparentSourceMethod,
} from '../context';

export interface CompileModulesOptions
  extends Omit<
    MemoDomOptions,
    | 'moduleId'
    | 'linkedImports'
    | 'linkedComponentPaths'
    | 'linkedComponentRows'
    | 'linkedComponentPropSources'
    | 'linkedComponentRenderProps'
  > {
  aliases?: Readonly<Record<string, string>>;
  resolveImport?: (specifier: string, importer: string) => string | undefined;
  linkFunctionSummaries?: boolean;
  /** Keep build graphs strict; editor-wide diagnostics can inspect multiple roots. */
  enforceSingleApplicationRoot?: boolean;
  frontend?: EstreeFrontend;
  /** Emit one browser program for an HTML document, when its initial content is proved.
   * A host predicate can validate its shell before emission. Direct JS entries omit this.
   */
  initialContent?: boolean | ((plan: InitialRenderPlan, delivery: InitialDelivery | undefined) => boolean);
  /** Internal server-page root inputs are available before rendering starts. */
  pageCaptureCount?: number;
  /** Experimental semantic summaries for separately compiled package entries. */
  experimentalPackageArtifacts?: readonly ExperimentalPackageArtifact[];
  /** Importer-specific package instances resolved by a host such as Vite. */
  experimentalPackageImports?: readonly ExperimentalPackageImport[];
}

export interface ExperimentalPackageFunctionSummary {
  transparentSourceFactory?: boolean;
  transparentSourceMethod?: TransparentSourceMethod;
  parameterWrites: ParameterWrite[];
  parameterSourceReads: ParameterSourceRead[];
  parameterPayloadReads: ParameterSourceRead[];
  unbounded: boolean;
}

export interface ExperimentalPackageComponentSummary
  extends Omit<ComponentExportInfo, 'key'> {
  /** Package-stable component identity used by the consuming component graph. */
  key: string;
  /** Closed package-owned DOM shape which an application may specialize. */
  initial?: ExperimentalPackageRenderPlan;
}

export type ExperimentalPackageRenderValue =
  | { readonly kind: 'literal'; readonly value: string | number | boolean | null }
  | { readonly kind: 'prop'; readonly name: string };

export interface ExperimentalPackageRenderAttribute {
  readonly name: string;
  readonly site: string;
  readonly value: ExperimentalPackageRenderValue;
}

export type ExperimentalPackageRenderNode =
  | {
      readonly kind: 'text';
      readonly parts: readonly ExperimentalPackageRenderValue[];
    }
  | {
      readonly kind: 'element';
      readonly tag: string;
      readonly site: string;
      readonly attributes: readonly ExperimentalPackageRenderAttribute[];
      readonly children: readonly ExperimentalPackageRenderNode[];
    }
  | {
      readonly kind: 'slot';
      /** Empty string denotes the default slot. */
      readonly name: string;
      readonly fallback: readonly ExperimentalPackageRenderNode[];
    };

/**
 * Deliberately small, non-executable initial DOM contract. It is generated by
 * package compilation and substituted only when the whole call is static.
 */
export interface ExperimentalPackageRenderPlan {
  readonly root: ExperimentalPackageRenderNode;
  /** The matching package factory accepts an optional host after its ordinary arguments. */
  readonly adoption?: 'host-v1';
}

export interface ExperimentalPackageEntry {
  functions: Record<string, ExperimentalPackageFunctionSummary>;
  components?: Record<string, ExperimentalPackageComponentSummary>;
}

/**
 * Versioned semantic metadata generated by the experimental package compiler.
 * It complements the emitted JavaScript; it is not executable code or the
 * recommended authoring surface for opaque runtime boundaries.
 */
export interface ExperimentalPackageArtifact {
  kind: 'memoized-dom-package';
  version: 1;
  entries: Record<string, ExperimentalPackageEntry>;
}

/** One host-resolved package import, kept separate from its portable artifact. */
export interface ExperimentalPackageImport {
  readonly importer: string;
  readonly specifier: string;
  /** Reproducible semantic instance identity, normally an artifact digest. */
  readonly instance: string;
  readonly artifact: ExperimentalPackageArtifact;
}

export interface StateExport {
  type: 'state';
  kind: StateKind;
  key: string;
  transparentSource?: boolean;
  tagCandidates: string[];
  componentCandidates: string[];
}

export interface FunctionExport {
  type: 'function';
  plainListReturn?: PlainListReturn;
  transparentSourceFactory?: boolean;
  transparentSourceMethod?: TransparentSourceMethod;
  tagCandidates: string[];
  componentCandidates: string[];
  reads: string[];
  opaqueReads?: boolean;
  writes: string[];
  boundedWrites: string[];
  parameterWrites: ParameterWrite[];
  parameterSourceReads: ParameterSourceRead[];
  parameterPayloadReads: ParameterSourceRead[];
  unbounded: boolean;
}

export interface ComponentExport extends ComponentExportInfo {
  type: 'component';
}

export interface ValueExport { type: 'value' }

export type LinkedExport =
  | StateExport
  | FunctionExport
  | ComponentExport
  | ValueExport;

export interface ImportRef {
  local: string;
  imported: string;
  source: string;
  at: BaseNode;
}

export type { ComponentPropUsage, RenderUsage } from '../components/render-usage';

export interface ModuleManifest {
  exports: Record<string, LinkedExport>;
  imports: ImportRef[];
  mounts: string[];
  components: ComponentGraphNode[];
  componentUsages: ComponentPropUsage[];
  routedPreparations: CompilerRoutedPreparation[];
  readers: Record<string, string[]>;
}

export interface ModuleEntry {
  originalId: string;
  id: string;
  source: string;
  ast: t.Program;
  comments?: readonly AstComment[];
  css?: string;
}

export interface LinkResolutionOptions {
  aliases?: Readonly<Record<string, string>>;
  resolveImport?: (specifier: string, importer: string) => string | undefined;
  linkFunctionSummaries?: boolean;
  experimentalPackageArtifacts?: readonly ExperimentalPackageArtifact[];
  experimentalPackageImports?: readonly ExperimentalPackageImport[];
}
